namespace DayManager.App.Controls;

/// <summary>
/// 文字可以被鼠标选中的 Label。
///
/// 【为什么非要自己做一个】
/// MAUI 的 Label 是"只能看的字"：拖选没有反应，Ctrl+C 复制出来的是上一次别处粘的内容。
/// 对话页里 AI 说的话经常是要搬到别处去的——粘进文档、发给别人、当搜索词，
/// 只能看不能选，就只剩"照着屏幕手打一遍"，而照抄是最容易出错也最磨人的那种重复劳动。
///
/// 【为什么不在输入框里显示这些字】
/// 换 Editor（只读）确实天然可选，但它是输入框样子：有光标、有内边距、
/// 换行 behave 跟 Label 不一样，还要额外处理"点进去能不能编辑"。
/// 而这个软件要的只是"字可以被拖选"这一条，
/// 用原生控件自己的开关打开就够了，不必换掉整个控件。
///
/// 【平台开关放哪】
/// 选中这件事必须落到原生控件上（Windows 是 WinUI 的 TextBlock，
/// Android 是 TextView），所以真正的赋值写在平台各自的映射里，
/// 这个类本身只是给 XAML 一个"我要可选"的标记。
/// </summary>
public class SelectableLabel : Label
{
}
