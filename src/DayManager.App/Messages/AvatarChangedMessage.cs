namespace DayManager.App.Messages;

/// <summary>
/// 某个头像被换掉了（换成自定义图，或者恢复成默认的那个图形）。
///
/// 【为什么需要这条消息】
/// 头像是画出来的，不是绑出来的：它由 GraphicsView 每次重绘时现读一次图片，
/// 不像 <c>Image.Source</c> 那样改了绑定就会自己刷新。
/// 而"换完头像、回到对话页看到的还是旧的那张"和最难受的那类 bug 长得很像
/// ——像是设置没生效。所以需要有人显式通知这些画面重画一次。
///
/// 【为什么不带"是哪一个槽"】
/// 重画一屏头像的成本是几十个小圆，远低于"判断哪个该重画"的代码复杂度；
/// 而两个头像几乎总是在同一屏上出现。一律全重，简单且不会漏。
/// </summary>
public sealed record AvatarChangedMessage;
