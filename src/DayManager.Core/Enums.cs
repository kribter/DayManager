namespace DayManager.Core.Enums;

/// <summary>
/// 一条记录（日程或待办）的生命周期状态。
/// </summary>
public enum ItemStatus
{
    /// <summary>还没开始</summary>
    Pending = 0,

    /// <summary>
    /// 进行中：已经开工，但还没做完。
    ///
    /// 【为什么不能只有 pending 和 done 两种状态】
    /// 这个状态是为你的核心痛点设计的。你说过瓶颈是"知道该做但启动不了"，
    /// 如果只有"未开始/已完成"，那么做到一半的事情在数据上和完全没碰过是一样的，
    /// 既没法告诉你"你已经迈出第一步了"，也没法统计启动到底花了多久。
    /// 有了这个状态，"开始"本身就成为一个值得记录的进步。
    /// </summary>
    InProgress = 1,

    /// <summary>已完成</summary>
    Done = 2,

    /// <summary>
    /// 放弃：承认这件事不做了，永不再出现。
    ///
    /// 【为什么要有"放弃"而不是让用户直接删除】
    /// 放弃和删除在数据意义上是完全不同的：删除是"这条记录是误建的"，
    /// 放弃是"这件事确实存在过，但我决定不做了"。
    /// 保留放弃状态，AI 才能从历史里发现"你常常放弃这一类任务"这类规律。
    ///
    /// 【为什么叫 Abandoned 而不叫 Cancelled】
    /// 需求文档（2.2）里定的五态用的就是"放弃"，代码和文档用同一个词，
    /// 将来读代码不用在脑子里做一次翻译。数值仍是 3，不影响已有的数据。
    /// </summary>
    Abandoned = 3,

    /// <summary>
    /// 跳过：今天不做了，但明天照常回来。
    ///
    /// 【为什么"跳过"要和"放弃"分开——这是五态里最容易做错的一处】
    /// 两者的区别不是文案，是**统计口径**：
    ///   跳过 = 我今天明确决定不做它，那它今天就不该算数（不计入完成率分母）
    ///   放弃 = 真的不做了，必须计入分母
    /// 合成一个态的后果是完成率失真：要么把合理的休息算成失败（挫败感），
    /// 要么把真正的放弃藏起来（自欺）。
    ///
    /// 【"明天照常回来"靠什么实现】
    /// 光有这个状态不够——第二天软件无从知道它是被跳过了还是该重新出现。
    /// 所以配一个 SkippedAt（跳过的时刻），判定规则见 ItemRepository：
    /// **只有"跳过发生在这一天或之后"才算处于跳过态**。
    /// 昨天跳过的，今天自动当作未开始重新出现，不需要每天跑批处理去改状态。
    /// </summary>
    Skipped = 4
}

/// <summary>
/// 这件事的性质：该做的，还是想做的。
///
/// 【为什么要把这两种分开（这是需求第三轮里最关键的一条，编号 C1）】
/// 逃避行为有一条隐藏的成因：一直在还「该做的事」的债，
/// 「想做的事」永远排不上号，于是人只能靠刷视频、打游戏来补偿自己。
/// 封杀娱乐应用没用（替代品是无限的），因为被堵住的是出口，不是缺口。
///
/// 把两类任务放进同一个列表之后，才可能给出一个真正的奖励：
/// 当你做完该做的事，系统主动把「想做的事」顶上来。
/// 这比任何一句"你真棒"都实在——它是真实的、具体的、你本来就想要的。
///
/// 【为什么用枚举而不是往 Tags 里塞一个标记】
/// Tags 是给人看的自由标签，今天写 "想做的"、明天写 "want"、后天写成 "娱乐"，
/// 代码就没法可靠地判断了。这是一个有明确业务含义的分类，必须是强类型。
/// </summary>
public enum ItemKind
{
    /// <summary>该做的：有外部约束或责任，不做会有后果。</summary>
    MustDo = 0,

    /// <summary>想做的：出于兴趣或自我提升，不做也没人追。</summary>
    WantToDo = 1
}

/// <summary>
/// 优先级。刻意只做三档。
///
/// 【为什么不做五档或者"重要紧急四象限"】
/// 选项越多，每次填写的决策成本越高，最后要么全部标成最高优先级失去意义，
/// 要么干脆懒得填。三档是"够用"和"不烦"之间的平衡点。
/// </summary>
public enum Priority
{
    Low = 0,
    Normal = 1,
    High = 2
}

/// <summary>
/// 项目状态。
/// </summary>
public enum ProjectStatus
{
    /// <summary>进行中的项目</summary>
    Active = 0,

    /// <summary>
    /// 已归档。
    ///
    /// 【为什么归档而不是删除】
    /// 项目完成后删除会把里面的任务一并抹掉，历史完成率数据就断了。
    /// 归档保留全部数据，但不再出现在日常界面里。
    /// </summary>
    Archived = 1
}

/// <summary>
/// 记录这条数据来自哪类设备。
/// </summary>
public enum DevicePlatform
{
    Windows = 0,
    Android = 1
}

/// <summary>
/// 某一天的性质。干预引擎要根据它调整松紧。
/// </summary>
public enum DayType
{
    /// <summary>普通工作日</summary>
    Workday = 0,

    /// <summary>周末</summary>
    Weekend = 1,

    /// <summary>
    /// 法定节假日。
    ///
    /// 【为什么把节假日和周末分开】
    /// 你的干预规则里，"节假日可以彻底放松"和"周末可以松一点但还是要动一动"
    /// 是两种不同的松紧程度，合并成一个就没法区分了。
    /// </summary>
    Holiday = 2,

    /// <summary>
    /// 调休上班日。
    ///
    /// 【为什么要专门定义这一个】
    /// 这是中国特色：为了凑长假，某些周日要正常上班，某些周五反而放假。
    /// 如果只按"周六周日就是周末"来判断，调休那天的干预力度会错得离谱——
    /// 明明要上班，软件却用周末的宽松标准对待你。
    /// </summary>
    AdjustedWorkday = 3
}

/// <summary>
/// 一次写操作是谁做的。
///
/// 【为什么要区分】
/// 撤销只覆盖 AI 的操作（决策 D4），所以"这条日志能不能撤"首先要看这里。
/// 用户自己的操作不建 undo 栈——改错了改回来就是一步的事。
/// </summary>
public enum ActionActor
{
    User = 0,
    Ai = 1
}

/// <summary>
/// 写操作的类型。
///
/// 【为什么要单独记，而不是统一叫"改了"】
/// 撤销时不同的操作要走不同的反向动作：
///   Create  → 撤销是把它软删掉（它本来就不存在）
///   Update  → 撤销是把改前的快照写回去
///   SoftDelete → 撤销是把墓碑清掉
/// 不分开记，撤销代码里就全是 if 猜。
/// </summary>
public enum ActionType
{
    Create = 0,
    Update = 1,
    StatusChange = 2,
    SoftDelete = 3,
    PolicyChange = 4
}

/// <summary>
/// 一个参数是"怎么变成现在这个值的"。
///
/// 【为什么要记来源】
/// 决策 D8 定了参数由 AI 动态校准，但**用户手动改过的项 AI 不再自动覆盖**（2.7）。
/// 没有这个字段，AI 就分不清"这个值是它上次调的"还是"用户自己定的"，
/// 于是要么把用户的设置改掉，要么永远不敢再调。
/// </summary>
public enum PolicySource
{
    /// <summary>冷启动的默认值，还没被任何人动过。</summary>
    Default = 0,

    /// <summary>AI 依据数据调过。</summary>
    Ai = 1,

    /// <summary>用户自己设的，AI 不得自动覆盖。</summary>
    User = 2
}

/// <summary>
/// 一个应用属于哪一类。
///
/// 【为什么只有三类，没有"游戏""视频""购物"这种细分】
/// 干预只需要回答一个问题：**现在该不该拦**。
/// 细分标签看起来更聪明，但每个标签都要用户自己维护，而他真正会点的是
/// "这个算娱乐"和"这个别管"两个按钮。多出来的分类只会让设置页变长、让人不想去设。
/// 以后真要做"哪类娱乐最耗时"的统计，再细分也不迟——那时是数据驱动，不是预设。
/// </summary>
public enum AppKind
{
    /// <summary>
    /// 还没标记。判定时先看内置名单，名单里没有就不干预。
    ///
    /// 【为什么"未标记"不能等同于"工作"】
    /// 等同于工作的话，新装的游戏永远拦不住——而你最可能忘记标记的，
    /// 恰恰是刚装上的那个东西。
    /// </summary>
    Neutral = 0,

    /// <summary>娱乐。连续用超过阈值就会被提醒。</summary>
    Entertainment = 1,

    /// <summary>工作。永不提醒，哪怕内置名单里把它算成娱乐（比如用 B 站看网课）。</summary>
    Work = 2
}
