namespace DayManager.Core.Ai;

/// <summary>
/// AI 说话的语气档位。
///
/// 【为什么要有这个开关，而不是定死一种语气】
/// 这个软件是要长期相处的，而"AI 该怎么跟我说话"是一件**口味会变**的事：
/// 心情好时想听两句人话，烦躁时一句多余的话都是骚扰。
/// 定死一种，等于替用户做了他每隔一段时间就会反悔的决定。
/// 所以做成可切换的三档，存在 policy_settings 里，随时能改、改完立刻生效。
///
/// 【为什么放在 Core 而不是 Api】
/// 提示词的措辞改错了，表现是"AI 说话变味了"——这种错误没有报错、没有日志，
/// 只能靠读一遍 AI 说的话才能发现。放 Core 让冒烟测试能直接断言
/// "三档文案各不相同、都非空、未知值会退到默认档"，不用真的调一次大模型。
///
/// 【三档的共同底线】
/// 无论哪一档都不许挖苦、不许审判、不许空泛鼓励。
/// 这不是口味问题：为了对抗逃避而做的软件里，
/// "你怎么又没做"和"加油你可以的"是同一种东西的两面——都是不看你究竟做了什么。
/// </summary>
public static class AiTone
{
    /// <summary>克制：现在这个样子。有事说事，不加多余的话。</summary>
    public const string Reserved = "reserved";

    /// <summary>温和：先接住再说事，关心要具体。</summary>
    public const string Warm = "warm";

    /// <summary>直接：更短更硬，不铺垫不安慰，数据说话。</summary>
    public const string Direct = "direct";

    /// <summary>
    /// 默认档。
    ///
    /// 【为什么默认是克制而不是温和】
    /// 温和写不好就变成廉价打鸡血，而那是这个软件最该避开的东西；
    /// 克制写不好只是显得冷淡，不会让人反感。默认应该选"失误代价小"的那一档，
    /// 想要温度的自己去切。
    /// </summary>
    public const string Default = Reserved;

    /// <summary>把库里读出来的原始值归一化。没设过、写坏了、或者是从没见过的档位，一律退回默认。</summary>
    public static string Parse(string? raw) => raw?.Trim().ToLowerInvariant() switch
    {
        Warm => Warm,
        Direct => Direct,
        _ => Reserved
    };

    public static string DisplayName(string tone) => tone switch
    {
        Warm => "温和",
        Direct => "直接",
        _ => "克制"
    };

    /// <summary>界面上那句说明。写在卡片里，让人知道自己选的是什么。</summary>
    public static string Description(string tone) => tone switch
    {
        Warm => "先接住再说事，关心具体的那件事。",
        Direct => "更短更硬，不铺垫不安慰。",
        _ => "有事说事，不加多余的话。"
    };

    /// <summary>
    /// 拼进提示词的【说话方式】那几条。
    ///
    /// 【为什么这里只有"怎么说"，没有写"说几句"】
    /// 早期这里写着"一次不超过三句"。那是怕它啰嗦，但代价是把人设一起锁死了：
    /// 一个人把它设定成会撒娇的角色，它最多也只敢在第三句末尾加个语气词，
    /// 因为前面那条"不超过三句"排在硬规矩里，谁都改不动。
    /// 篇幅是口味，不是格式——想短的人在人设里写一句"别废话"就短了。
    /// 所以这里只保留"别绕圈子"这类**写法习惯**，句数完全交出去。
    ///
    /// 【为什么只管"说话方式"，不动别的】
    /// 输出格式、状态语义、改动规矩这些不是口味，
    /// 改了会让系统接不住回复或者弄丢事情。这里只替换这一小段。
    /// </summary>
    public static IReadOnlyList<string> StyleLines(string tone) => tone switch
    {
        Warm => new[]
        {
            "- 先把最要紧的那句说出来，别为了铺垫绕圈子。",
            "- **先接住再说事**：他说累、烦、不想动的时候，先认这件事本身难，再给下一步。",
            "- 记得他最近做过什么、卡在哪。能提到就提一句，那是「有人看着」的感觉的来源。",
            "- 不许空泛鼓励（「加油」「你可以的」这类话一句都不要）。",
            "  要关心就关心具体的那件事——他要的是有人真正在看，不是有人在对他念稿。",
            "- 不许挖苦、不许审判、不许说「你又没做」。"
        },
        Direct => new[]
        {
            "- 把最要紧的那句放在最前面，不铺垫、不寒暄、不解释原因。",
            "- 有事说事：只给下一步。",
            "- 该说难听的事实就直说（比如连着几天没做完），但不许挖苦、不许审判。"
        },
        _ => new[]
        {
            "- 先把结果和最要紧的那句说出来，别的往后排。",
            "- 给他一个最小、最具体的下一步。",
            "- 不空泛鼓励（「加油」「你可以的」这类话一句都不要）。",
            "- 连续几天完成率低时可以直接严肃，但**不许挖苦、不许审判**。"
        }
    };

    /// <summary>
    /// 人设最多能写多少字。
    ///
    /// 【为什么给上限，而不是随便写】
    /// 这段每次请求都会拼进系统提示词，是要反复付费、反复占上下文的。
    /// 500 字够写清楚一个身份、一段关系、几句口癖和篇幅要求，
    /// 再多就不是设定，是小说了——而写小说的人有更好的地方写。
    /// </summary>
    public const int MaxPersonaLength = 500;

    /// <summary>
    /// 把界面上填进来的人设收拾干净：去首尾空白、超过上限就截。
    ///
    /// 【为什么截断而不是报错】
    /// 这是他自己的设定文本，截掉尾巴不会让系统出错，只是少了几句；
    /// 而弹一个"你写太多了"要他回去删字，是在给一件不严肃的事上纪律。
    /// </summary>
    public static string NormalizePersona(string? raw)
    {
        if (string.IsNullOrWhiteSpace(raw))
        {
            return string.Empty;
        }

        var text = raw.Replace("\r\n", "\n").Replace('\r', '\n').Trim();

        return text.Length <= MaxPersonaLength ? text : text[..MaxPersonaLength];
    }

    /// <summary>
    /// 拼进提示词的【做成事之后】那几条。三档**都有**，不随语气开关。
    ///
    /// 【为什么这一块从"温和档里的一行"变成所有档都有的固定环节】
    /// 实测出来的一句话是这样：他把「线条」那条做完，AI 回的是
    /// 「挂上了，今天一条，没定时间也没估时长」——一次纯粹的记账。
    /// 做成一件事在界面上只有一次系统回执，没有任何人味的那半句，
    /// 于是"做完"这件事在系统里是静音的，而静音会让他不想再开始第二次。
    ///
    /// 【为什么它写在 StyleLines 之后、人设之前】
    /// 这样它是**默认值**：不管哪一档都会给，但人在人设里写
    /// "别夸我，我只想知道下一步"就能把它关掉。
    /// 要是写成硬规矩（排在人设后面），想要冷一点的人反而关不掉。
    ///
    /// 【为什么仍然禁止空泛鼓励】
    /// "加油你可以的"和"你怎么又没做"是同一种东西的两面——都不看他究竟做了什么。
    /// 这里要的是"点出他刚做完的是哪一件"，不是表扬稿。
    /// </summary>
    public static IReadOnlyList<string> FeedbackLines(string tone)
    {
        // 三档共用：先为"他做成了这件事"说一句，再谈下一步。
        var lines = new List<string>
        {
            "- 他做成一件事时（自己打勾，或让你标成已完成），**先为这件事说一句**，再给下一步。",
            "  说**他刚做成的是哪一件**：「线条那页画满了」是对的，「做得不错」是错的。",
            "  没有做完的事、没有数据支撑的话，都不要拿来充这一句。",
            "- 那天没什么可肯定的就不给——宁可省掉，也不要为了凑而凑。"
        };

        // 只有"怎么说"这一句按档位不同，要不要给这件事三档一致。
        lines.Add(tone switch
        {
            Warm => "- 那句可以带温度，但要落在刚做完的那件事上，不要变成表扬。",
            Direct => "- 那句要短要实在，落到做完的量上，说完立刻进下一步。",
            _ => "- 那句点到为止，一件事一句，话留给下一步。"
        });

        lines.Add("- 不许空泛鼓励（「加油」「真棒」「你可以的」一律不要用）。");
        lines.Add("- 不许挖苦、不许审判。");

        return lines;
    }
}
