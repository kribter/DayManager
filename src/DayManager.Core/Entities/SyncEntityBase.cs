namespace DayManager.Core.Entities;

/// <summary>
/// 所有需要跨设备同步的实体的基类。
///
/// 【为什么单独抽一个基类】
/// 同步系统的核心难题是：电脑和手机可能各自修改了同一条数据，联网时要能判断谁的版本更新、
/// 谁删了什么东西。下面这四个字段是业界的通用解法，每一个都有不可替代的作用。
/// 把它们放在基类里，是为了保证以后新增的任何表都不会漏掉同步能力。
/// </summary>
public abstract class SyncEntityBase
{
    /// <summary>
    /// 全局唯一标识。
    ///
    /// 【为什么用 Guid 而不是数据库自增 ID】
    /// 自增 ID 必须由服务端统一分配。而你的场景里，手机离线时也要能创建记录，
    /// 那一刻根本连不上服务端，拿不到合法 ID；如果让客户端自己生成数字 ID，
    /// 手机和电脑各自生成的 ID 一定会撞车。
    /// Guid 可以在完全离线的情况下由客户端本地生成，且撞车的概率低到可以忽略。
    /// </summary>
    public Guid Id { get; set; }

    /// <summary>
    /// 版本号，每次更新 +1。
    ///
    /// 【为什么有了更新时间还需要版本号】
    /// 时间戳依赖两台设备的系统时钟一致。一旦某台设备的时钟慢了几分钟，
    /// 它刚改的数据就会被误判成"旧数据"而被覆盖掉，而且这个过程极其隐蔽。
    /// 版本号的做法是：客户端提交修改时带上"我是基于版本 3 改的"，
    /// 服务端一看库里已经是版本 4，就知道这中间有别的设备改过，于是识别出冲突。
    /// 这种检测方式完全不依赖时钟。
    /// </summary>
    public int Version { get; set; }

    /// <summary>
    /// 创建时间。
    ///
    /// 【为什么必须有 CreatedAt，光有 UpdatedAt 不够】
    /// 你自己的痛点是"知道该做但启动不了"，对应的核心指标是「启动延迟」：
    ///     启动延迟 = StartedAt（真正开始的时间） - CreatedAt（想到要做的时刻）
    /// 没有 CreatedAt，这个减法无从下手，我们就只能统计"完成率"这种结果指标，
    /// 而看不到过程有没有在改善。
    ///
    /// 【为什么不能拿 UpdatedAt 顶替】
    /// UpdatedAt 每次修改都会刷新。假设你在晚上八点把早上创建的任务改了个错别字，
    /// UpdatedAt 就变成了晚上八点，算出来的"延迟"完全是假的。
    /// 创建时间必须是只写一次、永不改变的值。
    /// </summary>
    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>
    /// 最后更新时间。
    ///
    /// 【为什么用 DateTimeOffset 而不是 DateTime】
    /// DateTime 不包含时区偏移量。假设你在北京的手机上把日程改成了 10:00，
    /// 而电脑上的时间是纽约时区，两个 10:00 无法直接比较先后。
    /// DateTimeOffset 会把偏移量一起存下来，可以精确排序。
    /// 这是跨时区应用最常见的 bug 来源，宁可一开始就选对类型。
    /// </summary>
    public DateTimeOffset UpdatedAt { get; set; }

    /// <summary>
    /// 删除时间（软删除墓碑）。
    ///
    /// 【为什么不直接从数据库删掉】
    /// 如果在手机上一键删除，服务端根本不知道"这条被删了"，
    /// 它只会认为这条记录从来没存在过，于是电脑上的同一条记录会永远残留。
    /// 软删除会留下一条"墓碑"，同步时把"已删除"这个事实传播出去，
    /// 其他设备收到墓碑后才在本地真正清理。
    /// 这是任何离线同步系统都绕不开的设计。
    /// </summary>
    public DateTimeOffset? DeletedAt { get; set; }

    /// <summary>
    /// 最后修改这条记录的设备标识。
    /// 用途是事后排查"这条记录到底是被谁改的"，排查同步问题时非常有用。
    /// </summary>
    public string? DeviceId { get; set; }
}
