namespace DayManager.Core.Entities;

/// <summary>
/// 一段"计时器开着"的时间：从点下启动那一刻，到暂停或完成那一刻。
///
/// 【为什么要有这张表，光有 Item.ActualMinutes 不够】
/// ActualMinutes 只是一个总数——它回答"这件事一共花了 125 分钟"，
/// 却回答不了"这 125 分钟是今天哪几个钟头"。而时间账需要的正是后者：
/// 判断"他今天有多少时间在做事"，必须知道那些分钟落在几点。
///
/// 你做纸上练习、看纸质书、出门办事的时候，电脑采集看不见你——
/// 那段时间的时长统计里等于不存在，分母只剩"坐在屏幕前的那几小时"，
/// 于是娱乐占比被系统性高估，AI 会说出"你今天都在玩"这种冤枉人的话。
/// 这张表就是补那个分母的：它是"他在做事"的直接证据，
/// 而且是他自己点下启动那一刻写下的，比任何从电脑行为反推的猜测都可靠。
///
/// 【为什么一段一段记，而不是记一个总数】
/// 中间暂停过的话，"从几点到几点"不是连续的一段。
/// 只记总数就只能拿完成时刻往前倒推，把吃饭、走神的时间也算成在做——
/// 那会让统计偏大。分段记是为了让每一段都有真实的起止。
///
/// 【时长为什么不单独存一列，而是用 EndAt - StartAt 算】
/// 这一段的语义就是"计时器开着的那段时间"，墙钟走多久它就是多久——
/// 中途离开该由他自己按暂停，不是由采集器猜。
/// 存一个算出来的数字反而会和起止时刻打架（改了一边忘了另一边）。
/// 需要时现算，两边永远一致。
/// </summary>
public class WorkSegment : SyncEntityBase
{
    /// <summary>这一段属于哪一条记录。</summary>
    public Guid ItemId { get; set; }

    /// <summary>导航属性。查询时方便带出标题，写的时候不用管它。</summary>
    public Item? Item { get; set; }

    /// <summary>计时器按下的那一刻。</summary>
    public DateTimeOffset StartAt { get; set; }

    /// <summary>
    /// 计时器停下的那一刻。
    ///
    /// 【为什么可空】
    /// 正在走的那一段还没有结束时刻。用 null 表示"还在计时"，
    /// 统计时拿"现在"当它的右端——否则他正在纸上做题的那两个小时
    /// 要等到点完成才进账，而他要的正是"此刻的占比别冤枉我"。
    /// </summary>
    public DateTimeOffset? EndAt { get; set; }
}
